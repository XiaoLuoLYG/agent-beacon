import Foundation
import Testing
@testable import AgentBeaconCore

@Test func detectorFindsCliFromPathAndBundledAppExecutable() throws {
    let fixture = try IntegrationFixture()
    try fixture.makeExecutable("bin/codex")
    try fixture.makeExecutable("Applications/Cursor.app/Contents/Resources/app/bin/cursor")

    let detector = AgentDetector(
        executableSearchPaths: [fixture.path("bin")],
        applicationSearchPaths: [fixture.path("Applications")],
        shimDirectoryURL: fixture.url("shims"),
        shellProfileURL: fixture.url(".zshrc")
    )

    let results = detector.detect()
    let codex = try #require(results.first { $0.definition.platform == .codex })
    let cursor = try #require(results.first { $0.definition.platform == .cursor })

    #expect(codex.cliPath == fixture.path("bin/codex"))
    #expect(cursor.cliPath == fixture.path("Applications/Cursor.app/Contents/Resources/app/bin/cursor"))
    #expect(cursor.appPath == fixture.path("Applications/Cursor.app"))
}

@Test func detectorSkipsExistingAgentBeaconShimsInPath() throws {
    let fixture = try IntegrationFixture()
    try fixture.makeExecutable(
        "old-shims/claude",
